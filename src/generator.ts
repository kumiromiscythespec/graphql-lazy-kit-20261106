export interface GeneratedFile { path: string; content: string }
export interface GeneratorPlugin {
  transformSchema?: (schema: GraphQLSchema) => GraphQLSchema | Promise<GraphQLSchema>;
  onFile?: (file: GeneratedFile) => GeneratedFile | Promise<GeneratedFile>;
}
export interface GenerateOptions {
  schema: SchemaInput;
  outDir: string;
  fragments?: string;
  scalars?: Record<string, string>;
  plugins?: GeneratorPlugin[];
}

const header = '// Generated by graphql-lazy-kit. Regenerate instead of editing.\n';
const quote = (value: string): string => JSON.stringify(value);
const typeName = (name: string): string => `GQL${name}`;
const selectionName = (name: string): string => `${name}Selection`;

export async function generate(options: GenerateOptions): Promise<{ files: string[]; schema: GraphQLSchema }> {
  if (!options.outDir?.trim()) throw new Error('outDir must name an output directory.');
  let schema = await loadSchema(options.schema);
  for (const plugin of options.plugins ?? []) {
    if (plugin.transformSchema) {
      schema = await plugin.transformSchema(schema);
      assertValidSchema(schema);
    }
  }
  const scalarMappings = { ID: 'string', String: 'string', Int: 'number', Float: 'number', Boolean: 'boolean', ...options.scalars };
  for (const [name, mapping] of Object.entries(options.scalars ?? {})) {
    if (!isScalarType(schema.getType(name))) throw new Error(`Scalar mapping "${name}" does not name a scalar in this schema.`);
    if (!mapping.trim()) throw new Error(`Scalar mapping "${name}" has an empty TypeScript type.`);
  }
  const fragments = await readFragments(schema, options.fragments);
  const types = Object.values(schema.getTypeMap()).filter(type => !type.name.startsWith('__')).sort((a, b) => a.name.localeCompare(b.name));
  const composites = types.filter(isCompositeType);
  const outputs: GeneratedFile[] = [
    { path: 'types.ts', content: generateTypes(schema, types, composites, fragments, scalarMappings) },
    { path: 'client.ts', content: generateClient(schema, composites) },
    { path: 'fragments.ts', content: generateFragmentLoader(fragments) },
    ...generateFragmentModules(fragments),
    { path: 'index.ts', content: `${header}export * from './types.js';\nexport * from './client.js';\nexport { fragmentNames, loadFragment } from './fragments.js';\nexport { createClient, GraphQLRequestError } from './runtime.js';\nexport type { BuiltOperation, FragmentSpec, SchemaMeta, GraphQLRequestErrorDetails } from './runtime.js';\n` },
  ];
  // Read the distributed runtime before touching the destination, so a broken installation fails atomically.
  try {
    outputs.push({ path: 'runtime.ts', content: await readFile(new URL('../src/runtime.ts', import.meta.url), 'utf8') });
  } catch (error) {
    throw new Error('Cannot locate distributed src/runtime.ts. Reinstall graphql-lazy-kit with its standalone runtime source.', { cause: error });
  }
  const destination = resolve(options.outDir);
  const prepared: GeneratedFile[] = [];
  const paths = new Set<string>();
  for (let file of outputs) {
    for (const plugin of options.plugins ?? []) if (plugin.onFile) file = await plugin.onFile({ ...file });
    if (!file || typeof file.path !== 'string' || typeof file.content !== 'string') {
      throw new Error('A plugin onFile hook must return { path: string, content: string }.');
    }
    const target = resolve(destination, file.path);
    const local = relative(destination, target);
    if (!local || local.startsWith(`..${sep}`) || local === '..' || isAbsolute(local)) {
      throw new Error(`Plugin output path escapes the output directory: ${file.path}`);
    }
    if (paths.has(target)) throw new Error(`Two generated files have the same output path: ${file.path}`);
    paths.add(target);
    prepared.push({ path: target, content: file.content });
  }
  for (const file of prepared) {
    await mkdir(dirname(file.path), { recursive: true });
    await writeFile(file.path, file.content, 'utf8');
  }
  return { files: prepared.map(file => file.path), schema };
}

interface Fragment { name: string; type: string; node: FragmentDefinitionNode; dependencies: string[] }

async function readFragments(schema: GraphQLSchema, input?: string): Promise<Fragment[]> {
  const source = input === undefined
    ? Object.values(schema.getTypeMap()).filter(isCompositeType).filter(type => !type.name.startsWith('__')).map(type => {
      const fields = isUnionType(type) ? [] : Object.values(type.getFields()).filter(field =>
        !isCompositeType(getNamedType(field.type)) && !field.args.some(arg => isNonNullType(arg.type) && arg.defaultValue === undefined),
      ).map(field => field.name);
      return `fragment ${type.name}Fields on ${type.name} { __typename ${fields.join(' ')} }`;
    }).join('\n')
    : await readTextInput(input, 'fragments');
  const document = parse(source);
  visit(document, { Variable(node) {
    throw new Error(`Fragment variable $${node.name.value} is not supported. Put arguments in typed builder selections so their variables can be bound.`);
  } });
  if (document.definitions.some(definition => definition.kind !== Kind.FRAGMENT_DEFINITION)) {
    throw new Error('The fragments input may contain fragment definitions only; put operations in your application.');
  }
  const problems = validate(schema, document, specifiedRules.filter(rule => rule !== NoUnusedFragmentsRule));
  if (problems.length) throw new Error(`Invalid GraphQL fragments:\n${problems.map(problem => `- ${problem.message}`).join('\n')}`);
  return document.definitions.map(definition => {
    const node = definition as FragmentDefinitionNode;
    const dependencies = new Set<string>();
    visit(node, { FragmentSpread(spread) { dependencies.add(spread.name.value); } });
    return { name: node.name.value, type: node.typeCondition.name.value, node, dependencies: [...dependencies].sort() };
  }).sort((a, b) => a.name.localeCompare(b.name));
}

function tsType(type: GraphQLType, leaf: (type: GraphQLNamedType) => string = named => typeName(named.name)): string {
  if (isNonNullType(type)) return nonNullableTs(type.ofType, leaf);
  return `${nonNullableTs(type, leaf)} | null`;
}
function nonNullableTs(type: GraphQLType, leaf: (type: GraphQLNamedType) => string): string {
  if (isNonNullType(type)) return nonNullableTs(type.ofType, leaf);
  if (isListType(type)) return `Array<${tsType(type.ofType, leaf)}>`;
  return leaf(type);
}
function scalarType(type: GraphQLNamedType, mappings: Record<string, string>): string {
  return mappings[type.name] ?? 'unknown';
}

function generateTypes(schema: GraphQLSchema, types: GraphQLNamedType[], composites: GraphQLCompositeType[], fragments: Fragment[], mappings: Record<string, string>): string {
  const declarations: string[] = [header];
  for (const type of types) {
    if (isScalarType(type)) declarations.push(`export type ${typeName(type.name)} = ${scalarType(type, mappings)};`);
    else if (isEnumType(type)) declarations.push(`export type ${typeName(type.name)} = ${type.getValues().map(value => quote(value.name)).join(' | ')};`);
    else if (isUnionType(type)) declarations.push(`export type ${typeName(type.name)} = ${type.getTypes().map(child => typeName(child.name)).join(' | ')};`);
    else if (isInputObjectType(type)) {
      declarations.push(`export type ${typeName(type.name)} = {\n${Object.values(type.getFields()).map(field =>
        `  ${quote(field.name)}${!isNonNullType(field.type) || field.defaultValue !== undefined ? '?' : ''}: ${tsType(field.type)};`,
      ).join('\n')}\n};`);
    } else if (isObjectType(type) || isInterfaceType(type)) {
      const typename = isObjectType(type) ? quote(type.name) : schema.getPossibleTypes(type).map(child => quote(child.name)).join(' | ') || 'string';
      declarations.push(`export type ${typeName(type.name)} = {\n  __typename: ${typename};\n${Object.values(type.getFields()).map(field => `  ${quote(field.name)}: ${tsType(field.type)};`).join('\n')}\n};`);
    }
  }
  declarations.push(`export interface SchemaTypes {\n${types.map(type => `  ${quote(type.name)}: ${typeName(type.name)};`).join('\n')}\n}`);
  const args: string[] = [];
  for (const parent of composites) {
    if (isUnionType(parent)) continue;
    for (const field of Object.values(parent.getFields())) if (field.args.length) {
      args.push(`  ${quote(`${parent.name}.${field.name}`)}: { ${field.args.map(arg => `${quote(arg.name)}${!isNonNullType(arg.type) || arg.defaultValue !== undefined ? '?' : ''}: ${tsType(arg.type)}`).join('; ')} };`);
    }
  }
  declarations.push(`export interface ArgumentTypes {\n${args.join('\n')}\n}`);
  for (const parent of composites) {
    const allowed = fragments.filter(fragment => {
      const condition = schema.getType(fragment.type);
      return condition && isCompositeType(condition) && doTypesOverlap(schema, parent, condition);
    }).map(fragment => quote(fragment.name)).join(' | ') || 'never';
    const fields = isUnionType(parent) ? [] : Object.values(parent.getFields()).map(field => `  ${quote(field.name)}?: ${fieldSelection(parent.name, field)};`);
    declarations.push(`export type ${selectionName(parent.name)} = {\n  __typename?: true;\n  $fragments?: readonly (${allowed})[];\n${fields.join('\n')}\n};`);
  }
  declarations.push(`export interface SelectionTypes {\n${composites.map(type => `  ${quote(type.name)}: ${selectionName(type.name)};`).join('\n')}\n}`);
  declarations.push(`export interface FragmentResultTypes {\n${fragments.map(fragment => {
    const parent = schema.getType(fragment.type) as GraphQLCompositeType;
    return `  ${quote(fragment.name)}: ${fragmentShape(schema, parent, fragment.node.selectionSet)};`;
  }).join('\n')}\n}`);
  declarations.push(`interface FragmentPossibleTypes {\n${fragments.map(fragment => {
    const parent = schema.getType(fragment.type) as GraphQLCompositeType;
    const possible = isObjectType(parent) ? quote(parent.name) : schema.getPossibleTypes(parent).map(type => quote(type.name)).join(' | ') || 'never';
    return `  ${quote(fragment.name)}: ${possible};`;
  }).join('\n')}\n}`);
  declarations.push(`type UnionToIntersection<U> = (U extends unknown ? (value: U) => void : never) extends ((value: infer I) => void) ? I : never;
type ObjectKeys<A> = A extends object ? keyof A : never;
type AllowedValue<A, K> = A extends object ? K extends keyof A ? A[K] : never : never;
/** Reject extra selection/argument/input keys even when valid keys are present. */
export type ExactSelection<S, A> = unknown extends A ? S : S extends readonly unknown[]
  ? Extract<NonNullable<A>, readonly unknown[]> extends readonly (infer E)[] ? { [K in keyof S]: ExactSelection<S[K], E> } : S
  : S extends object ? { [K in keyof S]: K extends ObjectKeys<NonNullable<A>> ? ExactSelection<S[K], AllowedValue<NonNullable<A>, K>> : never } : S;
type ApplicableFragment<V, N extends keyof FragmentResultTypes> = [V] extends [{ __typename: infer Name }]
  ? [Name] extends [FragmentPossibleTypes[N]] ? FragmentResultTypes[N] : Partial<Omit<FragmentResultTypes[N], '__typename'>>
  : Partial<FragmentResultTypes[N]>;
type FragmentResults<V, S> = S extends { $fragments: readonly (infer N)[] }
  ? [N] extends [never] ? {} : UnionToIntersection<N extends keyof FragmentResultTypes ? ApplicableFragment<V, N> : {}>
  : {};
type SelectedValue<V, S> = V extends null | undefined ? V : V extends readonly (infer E)[]
  ? Array<SelectedValue<E, S>> : S extends { select: infer C } ? SelectionResult<V, C> : V;
export type SelectionResult<V, S> = { [K in keyof S as K extends keyof V ? K : never]: K extends keyof V ? SelectedValue<V[K], S[K]> : never } & FragmentResults<V, S>;`);
  const query = schema.getQueryType();
  const mutation = schema.getMutationType();
  if (query) {
    if (query.name !== 'Query') declarations.push(`export type QuerySelection = ${selectionName(query.name)};`);
    declarations.push(`export type QueryResult<S extends QuerySelection> = SelectionResult<${typeName(query.name)}, S>;`);
  }
  if (mutation) {
    if (mutation.name !== 'Mutation') declarations.push(`export type MutationSelection = ${selectionName(mutation.name)};`);
    declarations.push(`export type MutationResult<S extends MutationSelection> = SelectionResult<${typeName(mutation.name)}, S>;`);
  }
  return declarations.join('\n\n') + '\n';
}

function fieldSelection(parent: string, field: GraphQLField<unknown, unknown>): string {
  const args = field.args.length ? `ArgumentTypes[${quote(`${parent}.${field.name}`)}]` : undefined;
  const required = field.args.some(arg => isNonNullType(arg.type) && arg.defaultValue === undefined);
  const named = getNamedType(field.type);
  if (isCompositeType(named)) return `{ ${args ? `args${required ? '' : '?'}: ${args}; ` : ''}select: ${selectionName(named.name)} }`;
  if (!args) return 'true';
  return `${required ? '' : 'true | '}{ args${required ? '' : '?'}: ${args} }`;
}

function fragmentShape(schema: GraphQLSchema, parent: GraphQLCompositeType, selections: SelectionSetNode): string {
  const fields: string[] = [];
  const extensions: string[] = [];
  for (const node of selections.selections) {
    if (node.kind === Kind.FRAGMENT_SPREAD) {
      const shape = `ApplicableFragment<${typeName(parent.name)}, ${quote(node.name.value)}>`;
      extensions.push(node.directives?.length ? `Partial<${shape}>` : shape);
    } else if (node.kind === Kind.INLINE_FRAGMENT) {
      const condition = node.typeCondition ? schema.getType(node.typeCondition.name.value) as GraphQLCompositeType : parent;
      const shape = fragmentShape(schema, condition, node.selectionSet);
      extensions.push(condition.name === parent.name && !node.directives?.length ? shape : `Partial<${shape}>`);
    } else {
      const name = node.alias?.value ?? node.name.value;
      const optional = node.directives?.some(directive => directive.name.value === 'skip' || directive.name.value === 'include') ? '?' : '';
      if (node.name.value === '__typename') {
        const typename = isObjectType(parent) ? quote(parent.name) : schema.getPossibleTypes(parent).map(type => quote(type.name)).join(' | ') || 'string';
        fields.push(`${quote(name)}${optional}: ${typename}`);
      } else if (!isUnionType(parent)) {
        const field = parent.getFields()[node.name.value];
        if (field) fields.push(`${quote(name)}${optional}: ${tsType(field.type, named => node.selectionSet && isCompositeType(named) ? fragmentShape(schema, named, node.selectionSet) : typeName(named.name))}`);
      }
    }
  }
  return [`{ ${fields.join('; ')} }`, ...extensions].join(' & ');
}

function generateClient(schema: GraphQLSchema, composites: GraphQLCompositeType[]): string {
  const roots = { query: schema.getQueryType()?.name, mutation: schema.getMutationType()?.name, subscription: schema.getSubscriptionType()?.name };
  const metaTypes: Record<string, { fields: Record<string, { type: string; args?: Record<string, string>; optionalArgs?: string[]; object?: string }> }> = {};
  for (const type of composites) {
    const fields: Record<string, { type: string; args?: Record<string, string>; optionalArgs?: string[]; object?: string }> = { __typename: { type: 'String!' } };
    if (!isUnionType(type)) for (const field of Object.values(type.getFields())) {
      const named = getNamedType(field.type);
      fields[field.name] = {
        type: String(field.type),
        ...(field.args.length ? { args: Object.fromEntries(field.args.map(arg => [arg.name, String(arg.type)])) } : {}),
        ...(field.args.some(arg => isNonNullType(arg.type) && arg.defaultValue !== undefined) ? { optionalArgs: field.args.filter(arg => isNonNullType(arg.type) && arg.defaultValue !== undefined).map(arg => arg.name) } : {}),
        ...(isCompositeType(named) ? { object: named.name } : {}),
      };
    }
    metaTypes[type.name] = { fields };
  }
  const imports = ['QuerySelection', 'QueryResult', 'ExactSelection', ...(roots.mutation ? ['MutationSelection', 'MutationResult'] : [])];
  return `${header}import { buildOperation, createClient, type BuiltOperation, type SchemaMeta } from './runtime.js';
import { loadFragment } from './fragments.js';
import type { ${imports.join(', ')} } from './types.js';

export const schemaMeta = ${JSON.stringify({ roots, types: metaTypes }, null, 2)} satisfies SchemaMeta;

export function buildQuery<const S extends QuerySelection>(selection: S & ExactSelection<S, QuerySelection>, operationName?: string): Promise<BuiltOperation<QueryResult<S>>> {
  return buildOperation<QueryResult<S>>(schemaMeta, 'query', selection, loadFragment, operationName);
}
${roots.mutation ? `
export function buildMutation<const S extends MutationSelection>(selection: S & ExactSelection<S, MutationSelection>, operationName?: string): Promise<BuiltOperation<MutationResult<S>>> {
  return buildOperation<MutationResult<S>>(schemaMeta, 'mutation', selection, loadFragment, operationName);
}
` : ''}
/** The underlying transport accepts these BuiltOperation<T> values and preserves T. */
export const createGeneratedClient = createClient;
`;
}

function generateFragmentLoader(fragments: Fragment[]): string {
  return `${header}import type { FragmentSpec } from './runtime.js';
export const fragmentNames = ${JSON.stringify(fragments.map(fragment => fragment.name))} as const;
export type FragmentName = typeof fragmentNames[number];
export async function loadFragment(name: string): Promise<FragmentSpec> {
  switch (name) {
${fragments.map(fragment => `    case ${quote(fragment.name)}: return (await import(${quote(`./fragments/${fragment.type}.js`)})).${fragment.name};`).join('\n')}
    default: throw new Error('Unknown generated fragment: ' + name);
  }
}
`;
}

function generateFragmentModules(fragments: Fragment[]): GeneratedFile[] {
  const groups = new Map<string, Fragment[]>();
  const lookup = new Map(fragments.map(fragment => [fragment.name, fragment]));
  for (const fragment of fragments) {
    const group = groups.get(fragment.type) ?? [];
    group.push(fragment);
    groups.set(fragment.type, group);
  }
  return [...groups].map(([type, group]) => {
    const imports: string[] = [];
    const checks: string[] = [];
    let index = 0;
    for (const fragment of group) for (const name of fragment.dependencies) {
      const dependency = lookup.get(name)!;
      if (dependency.type !== type) {
        const alias = `Dependency_${index++}`;
        imports.push(`import type { ${name} as ${alias} } from ${quote(`./${dependency.type}.js`)};`);
        checks.push(`type Check_${alias} = typeof ${alias};`);
      } else checks.push(`type Check_${index++} = typeof __generatedFragment_${name};`);
    }
    return { path: `fragments/${type}.ts`, content: `${header}import type { FragmentSpec as RuntimeFragmentSpec } from '../runtime.js';\n${imports.join('\n')}\n${checks.join('\n')}\n${group.map(fragment =>
      `const __generatedFragment_${fragment.name}: RuntimeFragmentSpec = ${JSON.stringify({ document: print(fragment.node), dependencies: fragment.dependencies }, null, 2)};\nexport { __generatedFragment_${fragment.name} as ${fragment.name} };`,
    ).join('\n\n')}\n` };
  });
}
